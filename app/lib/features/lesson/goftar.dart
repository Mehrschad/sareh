// گفتارِ سیمرغ — سطرهای دلگرمی.
//
// دو قاعده‌ی سخت:
//
//   ۱. لحن پیشنهادگر است، نه داور (ETHICS بخش ۲). سیمرغ می‌ستاید، هرگز
//      سرزنش نمی‌کند؛ برای منزلِ پرلغزش هم سطرش رو به پیش است.
//   ۲. هر واژه‌ی این سطرها باید خودش سره باشد. اپی که واژه‌ی پارسی
//      می‌آموزاند و «احسنت! عالی بود!» می‌گوید، خودش را نقض کرده.
//
// سطرِ هر بار از روی یک شمارنده برگزیده می‌شود، نه تصادفی: تصادف در
// آزمون‌ها آشوب می‌سازد و کاربر سطرِ تکراری را دو بارِ پیاپی می‌بیند.
// چرخشِ قطعی هر دو را حل می‌کند.
//
// ── چرا این‌قدر بیشتر از نسخه‌ی نخست ──
//
// نخست تنها پایانِ منزل دلگرمی داشت — یعنی هر ده دوازده پاسخ، یک بار.
// این برای بازخوردِ رفتاری بسیار دیر است: آنچه کوشش را نگه می‌دارد،
// نشانه‌های ریز و پیاپی است، نه یک جشنِ دور. پس اکنون سه لایه هست:
//
//   • هر پاسخِ درست، یک واژه‌ی کوتاهِ ستایش  (بی‌درنگ)
//   • هر سه درستِ پیاپی، یک سطرِ زنجیره       (میانِ منزل)
//   • پایانِ منزل، سطرِ بلندِ سیمرغ            (پایان)
//
// و انبان‌ها آن‌قدر بزرگ‌اند که تکرار زود به چشم نیاید — سطرِ تکراری،
// خودش ستایش را بی‌ارزش می‌کند.

import 'dart:math' as math;

/// یک سطرِ گفتار، با گوینده‌اش اگر از شاهنامه آمده باشد.
class GoftarLine {
  const GoftarLine(this.text, {this.by});

  final String text;

  /// «فردوسی» — تنها برای سطرهایی که راست از شاهنامه‌اند.
  final String? by;
}

class Goftar {
  const Goftar._();

  /// ستایشِ کوتاهِ هر پاسخِ درست. یک تا دو واژه، چون در نوارِ بازخورد
  /// کنارِ واژه‌ی آموخته می‌نشیند و نباید جایش را تنگ کند.
  static const List<String> praise = [
    'آفرین!',
    'درست!',
    'همین است!',
    'نیکو!',
    'زه!',
    'خوب رفتی!',
    'به‌جا بود!',
    'چه خوب!',
    'دقیق!',
    'بی‌لغزش!',
    'روشن شد!',
    'همان بود!',
  ];

  /// سطرِ زنجیره — وقتی چند پاسخِ درستِ پیاپی می‌آید.
  ///
  /// نمایه از روی شمارِ زنجیره برگزیده می‌شود، پس هرچه زنجیره بلندتر،
  /// سطر پرشورتر: پاداشِ فزاینده، بی‌آنکه چیزی تصادفی باشد.
  static const List<String> streak = [
    'سه تا پیاپی — گرم شدی!',
    'چهارتا! دستت روان است.',
    'پنج‌تا بی‌لغزش — سیمرغ می‌بیند.',
    'شش‌تا! این دیگر بخت نیست.',
    'هفت‌تا پیاپی — به‌اندازه‌ی هفت خان!',
    'هشت‌تا! نمی‌ایستی؟',
    'نه‌تا — واژه‌ها تسلیم شدند.',
    'ده‌تا پیاپی! امروز روزِ توست.',
  ];

  /// پایانِ منزلِ معمولی — دلگرمی برای ادامه.
  static const List<GoftarLine> station = [
    GoftarLine('آفرین! واژه‌ها یک‌به‌یک روشن می‌شوند.'),
    GoftarLine('پیش برو — راه، رونده را می‌خواهد.'),
    GoftarLine('هر واژه که می‌آموزی، اخگری است که می‌افروزی.'),
    GoftarLine('زبانِ نیاکان در دهانِ تو جان می‌گیرد.'),
    GoftarLine('گامی دیگر، و راه کوتاه‌تر.'),
    GoftarLine('سیمرغ بال گشوده — تو هم گام بگشا.'),
    GoftarLine('واژه‌ای که امروز آموختی، فردا از دهانت می‌پرد.'),
    GoftarLine('این منزل هم از آنِ تو شد.'),
    GoftarLine('کم‌کم دارد زبانت سره می‌شود.'),
    GoftarLine('هر بار که می‌آیی، چیزی از یادرفته بازمی‌گردد.'),
    GoftarLine('راه دراز است، ولی تو ایستاده‌ای در آن.'),
    GoftarLine('واژه‌ها آموختنی‌اند؛ تو داری می‌آموزی.'),
  ];

  /// منزلِ بی‌لغزش — ستایشِ ویژه.
  static const List<GoftarLine> perfect = [
    GoftarLine('بی‌لغزش! فَرّ بر تو می‌بارد.'),
    GoftarLine('همه درست — چشمِ سیمرغ روشن!'),
    GoftarLine('توانا بود هر که دانا بود', by: 'فردوسی'),
    GoftarLine('ز دانش دلِ پیر بُرنا بود', by: 'فردوسی'),
    GoftarLine('یکی هم نلغزید — این کارِ هر کسی نیست.'),
    GoftarLine('چنان رفتی که گویی از پیش می‌دانستی.'),
    GoftarLine('بسی رنج بردم در این سال سی', by: 'فردوسی'),
    GoftarLine('عجم زنده کردم بدین پارسی', by: 'فردوسی'),
    GoftarLine('پاک و بی‌لغزش — همان که «سره» یعنی همین.'),
  ];

  /// منزلی که لغزش داشت ولی گذشت — رو به پیش، بی‌سرزنش.
  static const List<GoftarLine> onward = [
    GoftarLine('گذشتی — و واژه‌های لغزیده دوباره به دیدنت می‌آیند.'),
    GoftarLine('لغزش، پله‌ی آموختن است. پیش برو.'),
    GoftarLine('به رنج اندرون است گنجِ سخن.'),
    GoftarLine('آنچه سخت آمد، همان است که می‌ماند.'),
    GoftarLine('هیچ‌کس بارِ نخست همه را نمی‌داند.'),
    GoftarLine('واژه‌ای که امروز نیامد، فردا می‌آید.'),
    GoftarLine('راه را رفتی؛ همین بس است.'),
    GoftarLine('کمی لغزیدی و نایستادی — این مهم‌تر است.'),
  ];

  /// ستایشِ کوتاهِ یک پاسخِ درست.
  ///
  /// [seen] شمارِ پاسخ‌های درستِ داده‌شده در همین منزل است؛ همان چرخش را
  /// قطعی می‌کند.
  static String forAnswer(int seen) => praise[seen % praise.length];

  /// سطرِ زنجیره، یا `null` اگر زنجیره هنوز به آستانه نرسیده.
  ///
  /// از [FarrRules.comboThreshold] آغاز می‌شود — همان‌جا که پاداشِ فَرّ
  /// هم آغاز می‌شود، تا کاربر ببیند چرا امتیازش بالا رفت.
  static String? forStreak(int run, {required int threshold}) {
    if (run < threshold) return null;
    return streak[math.min(run - threshold, streak.length - 1)];
  }

  /// سطرِ درخورِ پایانِ یک منزل.
  ///
  /// [completedBefore] شمارِ منزل‌هایی است که کاربر پیش‌تر گذرانده؛ همان
  /// شمارنده، چرخشِ سطرها را قطعی می‌کند.
  static GoftarLine forStation({
    required bool isPerfect,
    required bool hadWrong,
    required int completedBefore,
  }) {
    final pool = isPerfect
        ? perfect
        : hadWrong
            ? onward
            : station;
    return pool[completedBefore % pool.length];
  }
}
